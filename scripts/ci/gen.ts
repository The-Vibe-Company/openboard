import { join } from "node:path";
import { createOpenApi } from "@openboard/server";
import { type CommandOption, type CommandReference, commandReference } from "@the-vibe-company/openboard-cli";

export interface Generated {
  path: string;
  content: string;
}

function formatJson(path: string, value: unknown): string {
  const formatted = Bun.spawnSync(
    [process.execPath, "x", "--no-install", "biome", "format", `--stdin-file-path=${path}`],
    { stdin: Buffer.from(JSON.stringify(value)), stderr: "inherit" },
  );
  if (!formatted.success) throw new Error(`Could not format ${path}`);
  return formatted.stdout.toString();
}

export const COMMANDS_PATH = "skills/openboard/references/commands.md";

const HEADER = `<!-- Generated by \`bun run gen\` from the contract and the CLI's command table; never edit by hand. -->

# \`ob\` command reference

Every \`ob\` client command with its usage, arguments, options, the errors it can print and the matching MCP tool.

- Board commands act on the board at \`BOARD_URL\`; \`--as <name>\` acts as a stored profile where a command allows it.
- \`--json\` prints the raw answer instead of the text view.
- A failure prints \`error: <code>: <message>\`, sometimes followed by \`reason:\` and \`next:\` lines.
- Exit codes: 0 success, 1 error, 2 misuse (\`error: invalid_request\` with the usage), 130 interrupted.
- Options come before \`--\`; every word after \`--\` is an argument, so text may start with \`--\`.
`;

function list(title: string, entries: readonly CommandOption[]): string[] {
  if (entries.length === 0) return [];
  return [`${title}:`, "", ...entries.map(({ name, meaning }) => `- \`${name}\`: ${meaning}`), ""];
}

function section(reference: CommandReference): string {
  const tools = reference.mcpTools.map((tool) => `\`${tool}\``).join(", ");
  return [
    `## \`${reference.command}\``,
    "",
    reference.summary,
    "",
    "```sh",
    reference.usage,
    "```",
    "",
    ...list("Arguments", reference.arguments),
    ...list("Options", reference.options),
    `Errors: ${reference.errors.map((code) => `\`error: ${code}\``).join(", ")}.`,
    "",
    `MCP tool: ${tools || "none"}.`,
    "",
    "Example:",
    "",
    "```sh",
    reference.example,
    "```",
    "",
  ].join("\n");
}

/** The skill's command reference: one section per \`ob\` command (docs/codebase.md 4.2). */
export function renderCommands(references: readonly CommandReference[]): string {
  return [HEADER, ...references.map(section)].join("\n");
}

export function generate(): Generated[] {
  const path = "packages/server/openapi.json";
  return [
    { path, content: formatJson(path, createOpenApi()) },
    { path: COMMANDS_PATH, content: renderCommands(commandReference()) },
  ];
}

export async function checkGenerated(root: string, files: Generated[]): Promise<string[]> {
  const problems: string[] = [];
  for (const { path, content } of files) {
    const file = Bun.file(join(root, path));
    if (!(await file.exists())) problems.push(`${path}: missing; run \`bun run gen\` and commit the result`);
    else if ((await file.text()) !== content)
      problems.push(`${path}: stale, differs from what \`bun run gen\` writes; run it and commit the result`);
  }
  return problems;
}

if (import.meta.main) {
  const root = join(import.meta.dir, "../..");
  const files = generate();
  if (process.argv.includes("--check")) {
    const problems = await checkGenerated(root, files);
    for (const problem of problems) process.stderr.write(`${problem}\n`);
    process.exitCode = problems.length > 0 ? 1 : 0;
  } else {
    for (const { path, content } of files) {
      await Bun.write(join(root, path), content);
      console.log(`Wrote ${path}`);
    }
  }
}
